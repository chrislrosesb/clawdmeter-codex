#!/usr/bin/env python3
"""Generate firmware/src/agent_faces.h from the Pluribus agent art.

Faces are baked into flash as raw RGB565 (little-endian), circle-cropped onto
black so they need no alpha on the AMOLED's black background.  Tori (champion)
gets three frames from the AgentRig heads for the "hey" loop; every other agent
uses its existing Pluribus avatar medallion.

Usage (Pillow required; the daemon venv has it):
    daemon/.venv/bin/python tools/gen_agent_faces.py [--pluribus ~/pluribus-2.0]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw

FACE_PX = 224
MINI_PX = 52
OUT = Path(__file__).resolve().parents[1] / "firmware" / "src" / "agent_faces.h"

# (agent id, name tint, medallion file). Ids match Pluribus agent ids.
AGENTS = [
    ("champion", 0x5CC3D1, None),  # Tori: AgentRig heads, below
    ("skeptic", 0xF08A5D, "skeptic-face.png"),
    ("sales-marketing", 0xE07FB0, "sales-marketing-face.png"),
    ("coach", 0xA9C27A, "coach-face.png"),
    ("fde", 0x6FB3E0, "fde-face.png"),
    ("darwin", 0xF5B94A, "darwin-face.png"),
    ("pluribus", 0x8DB6EC, "pluribus-face.png"),
]
TORI_TEAL = (36, 142, 156)


def circle(img: Image.Image, size: int) -> Image.Image:
    """Return an RGB image: img circle-cropped onto black, antialiased edge."""
    big = size * 4
    src = img.convert("RGBA").resize((big, big), Image.LANCZOS)
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, big - 1, big - 1), fill=255)
    out = Image.new("RGB", (big, big), (0, 0, 0))
    out.paste(src, (0, 0), Image.composite(src.getchannel("A"), mask, mask))
    return out.resize((size, size), Image.LANCZOS)


def tori_head(rig: Path, pose: str) -> Image.Image:
    head = Image.open(rig / f"head-{pose}.png").convert("RGBA")
    crop = head.crop((70, 30, 370, 330))
    bg = Image.new("RGBA", crop.size, TORI_TEAL + (255,))
    bg.alpha_composite(crop)
    return bg


def words(img: Image.Image) -> list[str]:
    px = []
    for r, g, b in img.getdata():
        px.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    # Two little-endian RGB565 pixels per 32-bit word (denser source text).
    return [f"0x{px[i] | (px[i + 1] << 16):08X}" for i in range(0, len(px), 2)]


def emit(name: str, img: Image.Image) -> str:
    w = words(img)
    rows = [", ".join(w[i:i + 12]) for i in range(0, len(w), 12)]
    return (f"static const uint32_t {name}[{len(w)}] = {{\n    "
            + ",\n    ".join(rows) + "\n};\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pluribus", type=Path,
                    default=Path.home() / "pluribus-2.0")
    args = ap.parse_args()
    res = args.pluribus / "apple/AgentAnimations/Sources/AgentAnimations/Resources"
    rig = args.pluribus / "apple/AgentRig/Sources/AgentRig/RigArt/champion"

    parts = [
        "#pragma once\n#include <stdint.h>\n\n"
        "// GENERATED by tools/gen_agent_faces.py from the Pluribus agent art.\n"
        "// Do not hand-edit. RGB565 little-endian, two pixels per uint32.\n\n"
        f"#define AGENT_FACE_PX {FACE_PX}\n#define AGENT_MINI_PX {MINI_PX}\n\n"
    ]
    table = []
    for agent, tint, medallion in AGENTS:
        sym = agent.replace("-", "_")
        if medallion is None:
            frames = {p: tori_head(rig, p) for p in ("neutral", "wink", "talk")}
            base = frames["neutral"]
            for pose, img in frames.items():
                parts.append(emit(f"face_{sym}_{pose}", circle(img, FACE_PX)))
            refs = (f"face_{sym}_neutral", f"face_{sym}_wink", f"face_{sym}_talk")
        else:
            base = Image.open(res / medallion)
            parts.append(emit(f"face_{sym}_neutral", circle(base, FACE_PX)))
            refs = (f"face_{sym}_neutral", "nullptr", "nullptr")
        parts.append(emit(f"face_{sym}_mini", circle(base, MINI_PX)))
        table.append(f'    {{"{agent}", 0x{tint:06X}, {refs[0]}, {refs[1]}, {refs[2]}, face_{sym}_mini}},')

    parts.append(
        "\nstruct AgentFaceArt {\n    const char* id;\n    uint32_t tint;\n"
        "    const uint32_t* face;  // neutral\n    const uint32_t* wink;  // nullptr = no extra frame\n"
        "    const uint32_t* talk;\n    const uint32_t* mini;\n};\n\n"
        "static const AgentFaceArt AGENT_FACE_ART[] = {\n" + "\n".join(table) + "\n};\n"
        f"#define AGENT_FACE_ART_COUNT {len(table)}\n"
    )
    OUT.write_text("".join(parts), encoding="ascii")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB source)")


if __name__ == "__main__":
    main()
